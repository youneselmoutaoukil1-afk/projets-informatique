z = np.linspace(-10, 10, 200)
sigma = 1 / (1 + np.exp(-z))

plt.figure(figsize=(8, 5))
plt.plot(z, sigma, coulor='steelblue',linewidth=2)
plt.title('Sigmoid Function')
plt.xlabel('z')
plt.ylabel('σ(z)')
plt.axhline(0.5, color='gray', linestyle='--', label = 'y=0.5')
plt.axvline(0, color='red', linestyle='--', label = 'x=0')
plt.legend()
plt.savefig('sigmoid_function.png',dpi=150)
plt.show()
plt.close()
